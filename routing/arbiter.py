"""Multi-model plan and solution arbitration."""

from __future__ import annotations
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class CandidatePlan(BaseModel):
    model_source: str
    plan_text: str
    estimated_steps: int
    confidence_score: float = Field(default=0.8, ge=0.0, le=1.0)


class ArbitrationResult(BaseModel):
    selected_plan: CandidatePlan
    total_candidates: int
    selection_reason: str
    alternatives: List[CandidatePlan] = Field(default_factory=list)


class EnsembleArbiter:
    """Arbitrates among candidate plans generated by distinct models or reasoning variants."""

    def __init__(self, step_penalty_weight: float = 0.05):
        self.step_penalty_weight = step_penalty_weight

    def score_candidate(self, candidate: CandidatePlan) -> float:
        # Score = confidence - (step_count * penalty)
        penalty = candidate.estimated_steps * self.step_penalty_weight
        return round(max(0.01, candidate.confidence_score - penalty), 4)

    def arbitrate(self, candidates: List[CandidatePlan]) -> ArbitrationResult:
        if not candidates:
            raise ValueError("Cannot arbitrate empty list of candidates.")

        scored = [(c, self.score_candidate(c)) for c in candidates]
        # Sort by composite score descending
        scored.sort(key=lambda x: x[1], reverse=True)

        winner, best_score = scored[0]
        alts = [c for c, _ in scored[1:]]

        reason = (
            f"Candidate from '{winner.model_source}' selected with composite score {best_score:.4f} "
            f"(confidence={winner.confidence_score:.2f}, steps={winner.estimated_steps})"
        )

        return ArbitrationResult(
            selected_plan=winner,
            total_candidates=len(candidates),
            selection_reason=reason,
            alternatives=alts,
        )
